#include <stdio.h>

int main(void) {
    int akeraios = 25;
    float dekadikos = 3.14f;
    double dipli_akriveia = 3.14159265359;
    char xaraktiras = 'K';
    unsigned int mi_prosimasmenos = 500;

    printf("int: %d\n", akeraios);
    printf("float: %f\n", dekadikos);
    printf("double: %lf\n", dipli_akriveia);
    printf("char: %c\n", xaraktiras);
    printf("unsigned int: %u\n", mi_prosimasmenos);
    return 0;
}
